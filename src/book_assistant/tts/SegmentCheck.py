"""
SegmentCheck.py — Detects the occasional failures of the Qwen3 models in a generated segment, so that it can be
generated again:

  - text skipped: the audio is too short for the words of the text (e.g. an end token generated right away);
  - speaker switch: the pitch (median F0) or the speaker embedding of the audio is too far from the ones of the
    reference audio of a cloned voice (see https://arxiv.org/abs/2609.16989).

The pitch and the speaker embedding are only checked for voices with a reference audio; the speaker embedding
also requires a model providing a speaker encoder (the Qwen3 Base model with MLX).
"""
from dataclasses import dataclass
import numpy as np
from book_assistant.Commons import debug

_MIN_VOICED_FRAMES = 20     # fewer voiced frames than this (~0.2 sec) don't give a reliable pitch


@dataclass(frozen=True)
class CheckParams:
    retries:                int     = 2         # retries of a failed segment; 0 disables the checks
    min_seconds_per_word:   float   = 0.15      # shorter audio means that part of the text was skipped
    max_pitch_ratio:        float   = 1.6       # max ratio between the median F0 of the segment and of the reference
    min_speaker_similarity: float   = 0.4       # min cosine similarity between the speaker embeddings
    min_similarity_seconds: float   = 3.0       # shorter segments don't give a reliable speaker embedding


@dataclass(frozen=True)
class Verdict:
    problem:    str | None      # None if the segment passed all the checks
    score:      tuple           # higher is better, to pick the best among failed attempts
    summary:    str             # the measurements, for the debug log

    @property
    def ok(self) -> bool:
        return self.problem is None


def _median_f0(audio: np.ndarray, sample_rate: int) -> float | None:
    """The median pitch of the voiced frames of *audio*, or None if there are too few."""
    import librosa
    f0, voiced, _ = librosa.pyin(audio, fmin=50, fmax=500, sr=sample_rate, frame_length=2048)
    f0 = f0[voiced]
    return float(np.median(f0)) if len(f0) >= _MIN_VOICED_FRAMES else None


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))


class SegmentChecker:

    def __init__(self, params: CheckParams):
        self._params = params
        self._references: dict[int, tuple[float | None, np.ndarray | None]] = {}    # id(tts) -> (F0, embedding)

    @property
    def params(self) -> CheckParams:
        return self._params

    def _reference(self, tts) -> tuple[float | None, np.ndarray | None]:
        """The median F0 and the speaker embedding of the reference audio of *tts*, computed once."""
        key = id(tts)
        if key not in self._references:
            f0 = embedding = None
            reference = tts.reference_audio()
            if reference is not None:
                audio, sample_rate = reference
                f0 = _median_f0(audio, sample_rate)
                embedding = tts.speaker_embedding(audio, sample_rate)
                debug(f"Reference of {tts.prefix()}: F0 {f0 or 0:.0f} Hz, "
                      f"speaker embedding {'available' if embedding is not None else 'not available'}")
            self._references[key] = (f0, embedding)
        return self._references[key]

    def check(self, tts, audio: np.ndarray, sample_rate: int, words: int) -> Verdict:
        """Checks a segment of *words* words generated by *tts*.

        :param tts:             the TTS that generated the audio
        :param audio:           the generated audio (mono)
        :param sample_rate:     the sample rate of the audio
        :param words:           the number of words of the text
        :return:                the verdict
        """
        p = self._params
        seconds = len(audio) / sample_rate
        minimum = words * p.min_seconds_per_word
        duration = (f"duration {seconds:.2f} sec (min {minimum:.2f} = {words} words x {p.min_seconds_per_word:g} sec)")
        if seconds < minimum:
            return Verdict(f"too short for {words} words ({seconds:.2f} sec, expected at least {minimum:.2f})",
                           (0, seconds), duration)

        ref_f0, ref_embedding = self._reference(tts)
        failures = []

        if ref_f0 is None:
            pitch = "pitch not checked (no reference audio or no pitch in it)"
        else:
            f0 = _median_f0(audio, sample_rate)
            if f0 is None:
                pitch = f"pitch not checked (fewer than {_MIN_VOICED_FRAMES} voiced frames; reference {ref_f0:.0f} Hz)"
            else:
                ratio = max(f0 / ref_f0, ref_f0 / f0)
                pitch = f"pitch {f0:.0f} Hz, reference {ref_f0:.0f} Hz, ratio {ratio:.2f} (max {p.max_pitch_ratio:g})"
                if ratio > p.max_pitch_ratio:
                    failures.append((f"pitch {f0:.0f} Hz too far from the reference {ref_f0:.0f} Hz (ratio {ratio:.2f})",
                                     (1, -ratio)))

        if ref_embedding is None:
            identity = "speaker similarity not checked (no reference audio or no speaker encoder)"
        elif seconds < p.min_similarity_seconds:
            identity = f"speaker similarity not checked (shorter than {p.min_similarity_seconds:g} sec)"
        else:
            embedding = tts.speaker_embedding(audio, sample_rate)
            if embedding is None:
                identity = "speaker similarity not checked (no speaker encoder)"
            else:
                similarity = _cosine(embedding, ref_embedding)
                identity = f"speaker similarity {similarity:.2f} (min {p.min_speaker_similarity:g})"
                if similarity < p.min_speaker_similarity:
                    failures.append((f"speaker similarity {similarity:.2f} below {p.min_speaker_similarity:g}",
                                     (2, similarity)))

        summary = f"{duration}; {pitch}; {identity}"
        if failures:
            problem, score = failures[0]
            return Verdict(problem, score, summary)
        return Verdict(None, (3, 0), summary)
